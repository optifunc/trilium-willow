import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { connect, request, testRoot } from './test-client.mjs';
const {browser,page}=await connect();
const fixture=JSON.parse(await readFile(new URL('evidence/chrome/report.json',testRoot),'utf8'));
const notes=JSON.parse(await readFile(new URL('spike-notes.json',testRoot),'utf8'));
const id=fixture.noteId,passed=[];
const pass=text=>{passed.push(text);console.log(text);};
const panes=page.locator(`.willow-spike[data-note-id="${id}"]:visible`);
let ro;
try {
  await page.setViewportSize({width:2300,height:960});
  await page.evaluate(id=>glob.appContext.tabManager.getActiveContext().setNote(id),notes.B);
  await page.evaluate(async id=>{const m=glob.appContext.tabManager,main=m.getActiveMainContext().ntxId;for(const c of [...m.noteContexts])if(c.ntxId!==main)await m.removeNoteContext(c.ntxId);await m.activateNoteContext(main);await m.getActiveContext().setNote(id);},id);
  await panes.locator('.willow-spike-host[data-ready="true"]').waitFor();
  const first=panes.first();
  await first.locator('[data-action=more]').click();await first.getByRole('menuitem',{name:'Hide UI',exact:true}).click();
  await first.locator('.willow-toolbar').waitFor({state:'hidden'});
  await request(page,'PUT',`notes/${id}/set-attribute`,{type:'label',name:'readOnly',value:''});
  ro=(await request(page,'GET',`notes/${id}/attributes`)).find(a=>a.name==='readOnly').attributeId;
  await first.locator('.mindmap[aria-readonly=true]').waitFor();
  assert.equal(await first.locator('.willow-toolbar').isVisible(),false);
  await first.getByText('This map is read-only.',{exact:true}).waitFor();
  await page.waitForTimeout(150);await first.focus();await page.keyboard.press('Shift+F10');await first.getByRole('menuitem',{name:'Show UI',exact:true}).click();
  await first.locator('.willow-toolbar').waitFor({state:'visible'});
  assert.equal(await first.locator('[data-action=insertChild]').isDisabled(),true);
  assert.equal(await first.locator('[data-action=plus]').isEnabled(),true);
  await request(page,'DELETE',`notes/${id}/attributes/${ro}`);ro=undefined;
  await first.locator('.mindmap[aria-readonly=false]').waitFor();
  pass('Hidden state survives read-only editor recreation; persistent notice, Show UI and viewport actions remain available');
  await page.evaluate(id=>glob.appContext.triggerCommand('openNewNoteSplit',{ntxId:glob.appContext.tabManager.getActiveContext().ntxId,notePath:id}),id);
  await page.waitForFunction(id=>[...document.querySelectorAll(`.willow-spike[data-note-id="${id}"]`)].filter(e=>e.clientWidth).length===2,id);
  await panes.nth(1).locator('.willow-spike-host[data-ready="true"]').waitFor();
  await first.locator('[data-action=more]').click();await first.getByRole('menuitem',{name:'Hide UI',exact:true}).click();
  await first.locator('.willow-toolbar').waitFor({state:'hidden'});
  await panes.nth(1).locator('.willow-toolbar').waitFor({state:'hidden'});
  await panes.nth(1).getByRole('button',{name:'Edit here',exact:true}).click();
  await first.locator('.mindmap[aria-readonly=true]').waitFor();
  assert.equal(await first.locator('.willow-toolbar').isVisible(),false);
  await panes.nth(1).locator('.willow-toolbar').waitFor({state:'hidden'});
  await page.waitForTimeout(150);await first.focus();await page.keyboard.press('Shift+F10');await first.getByRole('menuitem',{name:'Show UI',exact:true}).click();
  await first.locator('.willow-toolbar').waitFor({state:'visible'});
  await panes.nth(1).locator('.willow-toolbar').waitFor({state:'visible'});
  pass('Two panes share UI visibility through editing ownership transfer');
  await page.evaluate(async()=>{const m=glob.appContext.tabManager,main=m.getActiveMainContext().ntxId;for(const c of [...m.noteContexts])if(c.ntxId!==main)await m.removeNoteContext(c.ntxId);await m.activateNoteContext(main);});
  await first.locator('[data-action=help]').click();
  await page.setViewportSize({width:400,height:700});
  const dialog=first.getByRole('dialog');await dialog.waitFor();
  const bounds=await dialog.boundingBox();assert.ok(bounds.x>=0&&bounds.x+bounds.width<=400);
  assert.equal(await dialog.evaluate(e=>e.scrollWidth<=e.clientWidth),true);
  assert.equal(await dialog.locator('.willow-shortcut-sections').evaluate(e=>getComputedStyle(e).gridTemplateColumns.split(' ').length),1);
  await page.emulateMedia({forcedColors:'active',reducedMotion:'reduce'});
  await dialog.getByRole('button',{name:'Done',exact:true}).click();assert.equal(await dialog.count(),0);
  await page.emulateMedia({forcedColors:'none',reducedMotion:'no-preference'});
  await page.setViewportSize({width:2300,height:960});
  pass('Narrow reference dialog uses one column without horizontal overflow; Done works with forced colors and reduced motion');
  await first.locator('[data-action=help]').click();await dialog.waitFor();
  await page.evaluate(id=>glob.appContext.tabManager.getActiveContext().setNote(id),notes.B);
  await page.locator(`.willow-spike[data-note-id="${notes.B}"] .willow-spike-host[data-ready="true"]`).waitFor();
  await page.waitForFunction(()=>!document.querySelector('.willow-shortcuts'));
  assert.equal(await page.locator('.willow-tooltip,.mindmap-menu').count(),0);
  pass('Disposing a pane with a modal open removes the dialog and its auxiliary DOM');
}finally{
  if(ro)await request(page,'DELETE',`notes/${id}/attributes/${ro}`).catch(()=>{});
  await writeFile(new URL('evidence/chrome/lifecycle.json',testRoot),JSON.stringify({testedAt:new Date().toISOString(),bundleSha256:notes.bundleSha256,passed},null,2)+'\n');
  await browser.close();
}
